CREATE TABLE talleres (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(160) NOT NULL, descripcion VARCHAR(2000) NOT NULL,
 area VARCHAR(100) NOT NULL, unidad_vecinal VARCHAR(160) NOT NULL,
 comuna VARCHAR(100) NOT NULL, direccion VARCHAR(200) NOT NULL,
 fecha_hora VARCHAR(50) NOT NULL, docente_lider VARCHAR(120) NOT NULL,
 cupos_maximos INTEGER NOT NULL CHECK(cupos_maximos > 0),
 version BIGINT NOT NULL DEFAULT 0
);
CREATE TABLE registros (
 id VARCHAR(36) PRIMARY KEY, owner VARCHAR(150) NOT NULL,
 tipo VARCHAR(20) NOT NULL, taller_id BIGINT NOT NULL REFERENCES talleres(id),
 participante VARCHAR(100) NOT NULL, rating INTEGER,
 comentario VARCHAR(2000), utilidad VARCHAR(30),
 registrado_en TIMESTAMP WITH TIME ZONE NOT NULL,
 recibido_en TIMESTAMP WITH TIME ZONE NOT NULL,
 CONSTRAINT un_registro_por_persona UNIQUE(tipo,taller_id,participante),
 CONSTRAINT rating_valido CHECK(rating IS NULL OR rating BETWEEN 1 AND 5)
);
